#!/usr/bin/env node
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';

const ROOT = '/home/runner/work/aeon/aeon';
const TODAY = '2026-11-08';
const OUTPUT_PATH = process.env.OUTPUT_PATH || 'docs/skill-graph.md';

const parsed = JSON.parse(readFileSync(join(ROOT, '.skill-graph-tmp/parsed.json'), 'utf8'));
const { skills, dependsEdges, sharedEdges, contentPipelineEdges, reactiveTriggers } = parsed;

// Canonical 6 categories
const CANON = ['research', 'dev', 'crypto', 'social', 'productivity', 'other'];
const CATEGORY_LABELS = {
  research: 'Research & Content',
  dev: 'Dev & Code',
  crypto: 'Crypto & Markets',
  social: 'Social',
  productivity: 'Productivity & Meta',
  other: 'Other & Uncategorized',
};

// Normalize category: if not in canonical list, remap by first-tag heuristic
function normalizeCategory(slug, cat, tags) {
  if (CANON.includes(cat)) return cat;
  // tag-derived remap
  const t = (tags[0] || '').toLowerCase();
  if (['research', 'article', 'paper', 'ai', 'ml', 'content'].includes(t)) return 'research';
  if (['dev', 'code', 'repo', 'security', 'devops', 'infra', 'data', 'eval'].includes(t)) return 'dev';
  if (['crypto', 'defi', 'token', 'compute', 'markets'].includes(t)) return 'crypto';
  if (['social', 'tweet', 'x'].includes(t)) return 'social';
  if (['productivity', 'meta', 'goal'].includes(t)) return 'productivity';
  return 'other';
}

const slugs = Object.keys(skills).sort();
for (const slug of slugs) {
  skills[slug].category = normalizeCategory(slug, skills[slug].category, skills[slug].tags);
}

// Collect per-category skill lists
const byCategory = Object.fromEntries(CANON.map(c => [c, []]));
for (const slug of slugs) {
  byCategory[skills[slug].category].push(slug);
}
for (const c of CANON) byCategory[c].sort();

// Enabled counts per category
const enabledByCategory = {};
for (const c of CANON) {
  enabledByCategory[c] = byCategory[c].filter(s => skills[s].enabled).length;
}

// Collapse edges: union across types for overview
// Build cross-category edge counts (any type)
const SELF_HEAL_LOOP = new Set(['heartbeat', 'skill-health', 'skill-evals', 'skill-repair', 'self-improve']);
function catOf(slug) { return skills[slug] ? skills[slug].category : null; }

function filterRealEdges(edges) {
  return edges.filter(e => skills[e.from] && skills[e.to]);
}

const dEdges = filterRealEdges(dependsEdges);
const sEdges = filterRealEdges(sharedEdges);
const cEdges = filterRealEdges(contentPipelineEdges);

const edgesTyped = [
  ...dEdges.map(e => ({ ...e, type: 'depends_on' })),
  ...sEdges.map(e => ({ ...e, type: 'shared_state' })),
  ...cEdges.map(e => ({ ...e, type: 'content' })),
];

// Overview cross-category tallies
const crossCount = {};  // "from->to" → n
for (const e of edgesTyped) {
  const fc = catOf(e.from), tc = catOf(e.to);
  if (!fc || !tc || fc === tc) continue;
  const key = `${fc}->${tc}`;
  crossCount[key] = (crossCount[key] || 0) + 1;
}

// Node ID helper — must be hyphenated (same as slug)
function nid(slug) { return slug; }
function label(slug) {
  const s = skills[slug];
  if (!s) return slug;
  if (s.enabled && s.schedule) {
    return `${slug}\\n${s.schedule}`;
  }
  return slug;
}

// Click-through path (relative to docs/)
function clickPath(slug) { return `../skills/${slug}/SKILL.md`; }

// Build Mermaid document
const lines = [];

// 1. Header
lines.push(`# Skill Dependency Graph`);
lines.push('');
lines.push(`> Auto-generated by \`skill-graph\` on ${TODAY}. Mode: \`SKILL_GRAPH_NEW\`.`);
lines.push('');

const verdictLine = `SKILL_GRAPH_NEW — ${slugs.length} skills mapped across ${CANON.length} categories, ${Object.values(enabledByCategory).reduce((a,b)=>a+b,0)} enabled`;
lines.push(`**Verdict:** ${verdictLine}`);
lines.push('');

// 2. Overview
lines.push('## Overview');
lines.push('');
lines.push('Category boxes show **enabled / total** skill counts. Cross-category edges carry their count.');
lines.push('');
lines.push('```mermaid');
lines.push('flowchart LR');
for (const c of CANON) {
  const en = enabledByCategory[c];
  const tot = byCategory[c].length;
  lines.push(`    subgraph ${c}["${CATEGORY_LABELS[c]} (${en} / ${tot})"]`);
  lines.push(`        ${c}_anchor( )`);
  lines.push('    end');
}
// draw cross-category edges, consistently ordered
const crossKeys = Object.keys(crossCount).sort();
for (const k of crossKeys) {
  const [f, t] = k.split('->');
  lines.push(`    ${f}_anchor -->|"${crossCount[k]}"| ${t}_anchor`);
}
for (const c of CANON) {
  lines.push(`    style ${c}_anchor fill:transparent,stroke:transparent`);
}
lines.push('```');
lines.push('');
lines.push('_Every skill also writes `memory/cron-state.json`, which is read by `heartbeat`, `skill-health`, `skill-repair`, and `skill-evals`. Collapsed here to keep the map readable — see Self-healing loop below._');
lines.push('');

// 3. Self-healing loop
lines.push('## Self-healing loop');
lines.push('');
const reactiveParts = [];
for (const [sk, trigs] of Object.entries(reactiveTriggers)) {
  for (const t of trigs) {
    reactiveParts.push(`\`${sk}\` fires on \`${t.when}\` for any skill (\`${t.on}\`)`);
  }
}
lines.push(`Reactive trigger: ${reactiveParts.join('; ')}.`);
lines.push('');
lines.push('```mermaid');
lines.push('flowchart LR');
const selfHealOrder = ['heartbeat', 'skill-health', 'skill-evals', 'skill-repair', 'self-improve'];
for (const s of selfHealOrder) {
  if (skills[s]) {
    lines.push(`    ${s}[${s}]`);
  } else {
    // still render (even if absent)
    lines.push(`    ${s}[${s}]`);
  }
}
lines.push(`    cron-state[("memory/cron-state.json")]`);
lines.push('    heartbeat --> skill-health');
lines.push('    skill-health --> skill-evals');
lines.push('    skill-evals --> skill-repair');
lines.push('    skill-repair --> self-improve');
lines.push('    heartbeat -.writes.-> cron-state');
lines.push('    skill-health -.reads.-> cron-state');
lines.push('    skill-repair -.reads.-> cron-state');
lines.push('    skill-evals -.reads.-> cron-state');
// style for enabled/disabled
for (const s of selfHealOrder) {
  const cls = (skills[s] && skills[s].enabled) ? 'enabled' : 'disabled';
  lines.push(`    class ${s} ${cls}`);
}
lines.push('    classDef enabled fill:#fff,stroke:#000,stroke-width:2px,color:#000');
lines.push('    classDef disabled fill:#f5f5f5,stroke:#bbb,color:#888');
// click bindings
for (const s of selfHealOrder) {
  if (skills[s]) lines.push(`    click ${s} "${clickPath(s)}"`);
}
lines.push('```');
lines.push('');

// 4. Per-category mini-diagrams
function edgeStyle(type) {
  if (type === 'depends_on') return '-->';
  if (type === 'consume') return '-.->';
  if (type === 'shared_state') return '-..->';
  if (type === 'content') return '-.->';
  return '-->';
}

for (const cat of CANON) {
  const members = byCategory[cat];
  if (!members.length) continue;
  lines.push(`## ${CATEGORY_LABELS[cat]}`);
  lines.push('');
  lines.push(`${enabledByCategory[cat]} enabled · ${members.length} total.`);
  lines.push('');
  // split into chunks of ~40 for readability
  const CHUNK = 40;
  const chunks = [];
  for (let i = 0; i < members.length; i += CHUNK) chunks.push(members.slice(i, i + CHUNK));
  for (let ci = 0; ci < chunks.length; ci++) {
    const chunk = chunks[ci];
    const chunkSet = new Set(chunk);
    lines.push('```mermaid');
    lines.push('flowchart LR');
    // in-category nodes
    for (const s of chunk) {
      lines.push(`    ${s}[${s}]`);
    }
    // intra-cat edges from this chunk
    const intraEdges = edgesTyped.filter(e => chunkSet.has(e.from) && chunkSet.has(e.to));
    for (const e of intraEdges) {
      lines.push(`    ${e.from} ${edgeStyle(e.type)} ${e.to}`);
    }
    // cross-cat edges from this chunk → external ghost nodes
    const extTargets = new Set();
    const extSources = new Set();
    for (const e of edgesTyped) {
      if (chunkSet.has(e.from) && catOf(e.to) !== cat && skills[e.to]) {
        extTargets.add(e.to);
      }
      if (chunkSet.has(e.to) && catOf(e.from) !== cat && skills[e.from]) {
        extSources.add(e.from);
      }
    }
    for (const t of [...extTargets].sort()) {
      lines.push(`    ${t}_ext[${t}]:::external`);
    }
    for (const s of [...extSources].sort()) {
      if (!extTargets.has(s)) lines.push(`    ${s}_ext[${s}]:::external`);
    }
    for (const e of edgesTyped) {
      if (chunkSet.has(e.from) && catOf(e.to) !== cat && skills[e.to]) {
        lines.push(`    ${e.from} ${edgeStyle(e.type)} ${e.to}_ext`);
      }
      if (chunkSet.has(e.to) && catOf(e.from) !== cat && skills[e.from]) {
        lines.push(`    ${e.from}_ext ${edgeStyle(e.type)} ${e.to}`);
      }
    }
    // enabled/disabled styling (applied to in-cat nodes)
    for (const s of chunk) {
      const cls = skills[s].enabled ? 'enabled' : 'disabled';
      lines.push(`    class ${s} ${cls}`);
      if (skills[s].enabled && skills[s].schedule) {
        // rewrite label in-place with schedule
        // We've already declared `s[s]`; add annotation via subscript edge
      }
    }
    lines.push('    classDef enabled fill:#fff,stroke:#000,stroke-width:2px,color:#000');
    lines.push('    classDef disabled fill:#f5f5f5,stroke:#bbb,color:#888');
    lines.push('    classDef external fill:none,stroke:#bbb,stroke-dasharray:3 3,color:#888');
    for (const s of chunk) {
      lines.push(`    click ${s} "${clickPath(s)}"`);
    }
    lines.push('```');
    if (chunks.length > 1) lines.push(`_Panel ${ci + 1} of ${chunks.length}._`);
    lines.push('');
  }
}

// 5. Legend
lines.push('## Legend');
lines.push('');
lines.push('- `A --> B` — `A` depends on `B` (declared `depends_on:`)');
lines.push('- `A -.-> B` — chain `consume:` (A reads B\'s output) **or** content-pipeline edge (research→syndicate/rss/gallery)');
lines.push('- `A -..-> B` — derived shared-state edge (A writes a topic/state file that B reads)');
lines.push('- **Bold-bordered node** — `enabled: true` in `aeon.yml`');
lines.push('- *Faded grey node* — `enabled: false` (defined but not scheduled)');
lines.push('- *Dashed-border node* — external ghost (cross-category target/source shown in the local panel; follow the click-through to its home category)');
lines.push('- **Click any node** on github.com to jump to its `SKILL.md`.');
lines.push('');
lines.push('Reactive hub note: `skill-repair` and `planner` listen on `consecutive_failures` thresholds for every skill in the fleet — they do not have per-skill edges drawn here. See the Self-healing loop callout above.');
lines.push('');

// 6. Summary table
lines.push('## Summary');
lines.push('');
lines.push('| Category | Enabled | Total | % enabled |');
lines.push('|---|---:|---:|---:|');
for (const c of CANON) {
  const en = enabledByCategory[c];
  const tot = byCategory[c].length;
  const pct = tot ? Math.round((en * 100) / tot) : 0;
  lines.push(`| ${CATEGORY_LABELS[c]} | ${en} | ${tot} | ${pct}% |`);
}
const totalEn = Object.values(enabledByCategory).reduce((a, b) => a + b, 0);
lines.push(`| **Total** | **${totalEn}** | **${slugs.length}** | **${Math.round(totalEn * 100 / slugs.length)}%** |`);
lines.push('');
lines.push('| Edge type | Count |');
lines.push('|---|---:|');
lines.push(`| \`depends_on\` | ${dEdges.length} |`);
lines.push(`| \`consume\` (active chains) | 0 |`);
lines.push(`| \`reactive\` | ${Object.values(reactiveTriggers).reduce((a, b) => a + b.length, 0)} |`);
lines.push(`| derived shared-state | ${sEdges.length} |`);
lines.push(`| content-pipeline | ${cEdges.length} |`);
lines.push('');

// 7. Source-status footer
const srcFooter = `skills parsed: ${slugs.length} · depends_on: ${dEdges.length} · consume: 0 · reactive: ${Object.values(reactiveTriggers).reduce((a, b) => a + b.length, 0)} · shared-state derived: ${sEdges.length} · content-pipeline: ${cEdges.length} · enabled: ${totalEn}/${slugs.length} · mode: SKILL_GRAPH_NEW`;
lines.push('---');
lines.push(`_${srcFooter}_`);
lines.push('');

const output = lines.join('\n');
const outPath = join(ROOT, OUTPUT_PATH);
writeFileSync(outPath, output);

// Lint checks
const lintErrors = [];
// 1. [label] brackets balance per declaration line
let openSubgraphs = 0;
for (const ln of output.split('\n')) {
  if (/^\s*subgraph\s/.test(ln)) openSubgraphs++;
  if (/^\s*end\s*$/.test(ln)) openSubgraphs--;
}
if (openSubgraphs !== 0) lintErrors.push(`subgraph balance ${openSubgraphs}`);

// 2. click paths exist
for (const ln of output.split('\n')) {
  const m = ln.match(/click\s+\S+\s+"([^"]+)"/);
  if (m) {
    const rel = m[1];
    // resolve relative to docs/
    const resolved = join(ROOT, 'docs', rel);
    if (!existsSync(resolved)) {
      // Try plain join for ../
      const alt = join(ROOT, 'docs', ...rel.split('/'));
      if (!existsSync(alt)) {
        lintErrors.push(`click path missing: ${rel}`);
      }
    }
  }
}

// Node-ID consistency: every edge references a declared node in some diagram.
// Simpler check: every edge `X --> Y` (etc.) has Y that is either defined (slug) or has _ext suffix in context.
// We'll skip exhaustive check since we controlled declaration.

if (lintErrors.length) {
  writeFileSync(join(ROOT, '.skill-graph-tmp/lint-errors.txt'), lintErrors.join('\n'));
  console.error('LINT ERRORS:', lintErrors.slice(0, 10));
  process.exit(2);
}

// Compute node_list_sha and edge_list_sha for state persistence
const nodeSha = createHash('sha1').update(slugs.join('\n')).digest('hex');
const edgeTuples = edgesTyped.map(e => `${e.from}|${e.to}|${e.type}`).sort();
const edgeSha = createHash('sha1').update(edgeTuples.join('\n')).digest('hex');

const state = {
  generated_at: TODAY,
  input_fingerprint: '6820630051553bb8c4049f225a10a8f3fca9b049',
  skills_total: slugs.length,
  enabled_count: totalEn,
  edges: {
    depends_on: dEdges.length,
    consume: 0,
    reactive: Object.values(reactiveTriggers).reduce((a, b) => a + b.length, 0),
    shared_state: sEdges.length,
    content_pipeline: cEdges.length,
  },
  node_list_sha: nodeSha,
  edge_list_sha: edgeSha,
};

writeFileSync(join(ROOT, 'memory/topics/skill-graph-state.json'), JSON.stringify(state, null, 2) + '\n');

console.log('Wrote', outPath);
console.log('Wrote state file');
console.log('LINT: OK');
console.log('Verdict:', verdictLine);
